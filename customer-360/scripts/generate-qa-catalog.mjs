// Generates packages/shared/src/qa-catalog.ts: the gold tables and columns the in-app Q&A may query.
// Source of truth is the generated connector entities, so the catalog cannot drift from what the app can read.
//
//   node scripts/generate-qa-catalog.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join('rayfin', 'connectors', 'c360lakehouse');
const DESCRIPTIONS = {
  GoldDimCustomer: 'One row per unified customer across ERP, Shopify, Klaviyo and Zendesk: type, name, region, owner, which systems they appear in, consent, lifecycle stage, active channels.',
  GoldCustomerMetrics: 'One row per Wholesale/Direct customer: last-12-month (TTM) and prior-year sales, YoY, returns, product lines bought, tickets, marketing engagement, churnRiskScore (0-100) with band and drivers (JSON), upsell score and value, revenueAtRisk, nextBestAction.',
  GoldCustomerMonthly: 'Customer x month: net sales, orders, returns, Klaviyo touches/engagements, Zendesk tickets, plus customerType/region/accountManager.',
  GoldCustomerProductLine: 'Customer x product line: TTM sales, share of the customer\'s sales, purchased flag, product views in 90 days, peer penetration.',
  GoldCustomerUpsell: 'Top 3 product-line upsell recommendations per customer with estimated annual value and reason.',
  GoldProductLinePenetration: 'Share of active customers (by customer type) who bought each product line, and average spend per buyer.',
  GoldSkuPerformance: 'SKU x customer type: TTM and prior sales, units, buyers, returns, defect returns, linked support tickets, return rate, YoY, repeat buyer rate.',
  GoldCustomerSku: 'Customer x SKU over 24 months: TTM and prior sales, units, returns, last purchase date.',
  GoldSkuAffinity: 'SKU pairs bought by the same customers ("bought together"): confidence and lift, top 5 per SKU.',
  GoldCustomerSkuRecs: 'Top 5 recommended SKUs per customer with estimated annual value and reason.',
  GoldIssueCascade: 'Event study by month relative to a support spike (relMonth -6..9): sales index vs. pre-spike baseline and marketing engagement rate, for "Support spike" vs. "No spike" cohorts.',
  GoldCustomerCascade: 'Customers with a support spike: spike month, engagement and monthly sales before/after, months until disengagement / sales decline, and pattern.',
  GoldDriverCorrelation: 'Correlation of each risk driver (measured 6 months ago) with the sales change since, by customer type.',
  GoldRiskConcentration: 'Revenue at risk by dimension (Region, Account owner, Product line, Risk band) and customer type.',
  GoldIdentityMergeCandidates: 'Pairs of customers that are probably the same person, with evidence and a match score.',
  GoldCustomerTimeline: 'Latest 25 events per customer: orders, returns, marketing clicks, support tickets.',
};

const tables = [];
for (const file of readdirSync(DIR).filter((f) => /^Gold.*\.ts$/.test(f)).sort()) {
  const src = readFileSync(join(DIR, file), 'utf8');
  const entity = /export class (\w+)/.exec(src)?.[1];
  const table = /table: '([^']+)'/.exec(src)?.[1];
  if (!entity || !table) continue;
  const columns = [...src.matchAll(/@(int|decimal|boolean|date|text|uuid)\([^)]*\) (\w+)[?!]?:/g)]
    .map(([, kind, name]) => ({ name, type: kind === 'int' || kind === 'decimal' ? 'number' : kind === 'date' ? 'date' : kind === 'boolean' ? 'boolean' : 'string' }));
  tables.push({ entity, table, description: DESCRIPTIONS[entity] ?? '', columns });
}

const out = `// @generated by scripts/generate-qa-catalog.mjs from rayfin/connectors/c360lakehouse. Do not edit by hand.
/** A column the in-app Q&A may read. */
export interface QaColumn { name: string; type: 'string' | 'number' | 'date' | 'boolean' }
/** A gold table the in-app Q&A may read (entity = connector entity name). */
export interface QaTable { entity: string; table: string; description: string; columns: QaColumn[] }

export const QA_CATALOG: readonly QaTable[] = ${JSON.stringify(tables, null, 2)};
`;
// Same file in both packages: the browser validates tool calls against it, the function describes it to Claude.
for (const pkg of ['shared', 'functions']) {
  writeFileSync(join('packages', pkg, 'src', 'qa-catalog.ts'), out);
  console.log(`Wrote ${tables.length} tables to packages/${pkg}/src/qa-catalog.ts`);
}
